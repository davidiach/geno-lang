#!/usr/bin/env python3
"""Build the Geno website.

    python3 website/build.py            # bundle + examples + blog
    python3 website/build.py --verify   # also check and test every example

Steps:

1. Zip the ``geno/`` package (without tests) into
   ``website/shared/playground/geno.zip`` for the in-browser playground,
   which loads it into Pyodide and runs the real CLI.
2. Generate ``website/shared/js/examples.js`` from ``shared/examples/*.geno``.
3. Render ``shared/posts/*.html`` into ``blog/`` through ``_templates/``,
   write an RSS feed, and refresh the "latest posts" block on the landing
   page.

The site itself is static HTML with no build-time dependencies; this script
only uses the standard library.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import subprocess
import sys
import tempfile
import zipfile
from dataclasses import dataclass, field
from datetime import date, datetime, timezone
from email.utils import format_datetime
from pathlib import Path

SITE = Path(__file__).resolve().parent
REPO = SITE.parent
SHARED = SITE / "shared"
SITE_URL = "https://geno-lang.org"

EXAMPLE_TITLES = {
    "welcome": "Examples as specs",
    "results": "Result and Option",
    "shapes": "Exhaustive matching",
    "pipelines": "Pipelines and lambdas",
    "traits": "Traits and impl",
    "contracts": "Contracts",
    "capabilities": "Capabilities",
}


# --------------------------------------------------------------------------
# 1. Playground bundle
# --------------------------------------------------------------------------
def build_bundle() -> Path:
    out = SHARED / "playground" / "geno.zip"
    out.parent.mkdir(parents=True, exist_ok=True)
    src = REPO / "geno"
    files = sorted(
        p
        for p in src.rglob("*")
        if p.is_file()
        and "tests" not in p.relative_to(src).parts
        and "__pycache__" not in p.parts
        and p.suffix not in {".pyc", ".pyo"}
    )
    with zipfile.ZipFile(
        out, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9
    ) as zf:
        for p in files:
            info = zipfile.ZipInfo(
                str(p.relative_to(REPO)), date_time=(2026, 1, 1, 0, 0, 0)
            )
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, p.read_bytes())
    print(
        f"bundle   {out.relative_to(REPO)}  {out.stat().st_size / 1024:.0f} KB, {len(files)} files"
    )
    return out


# --------------------------------------------------------------------------
# 2. Examples
# --------------------------------------------------------------------------
def build_examples(verify: bool) -> None:
    items = []
    for path in sorted((SHARED / "examples").glob("*.geno")):
        key = path.stem.split("-", 1)[1]
        source = path.read_text()
        blurb = ""
        for line in source.splitlines():
            if line.startswith("//"):
                blurb += (" " if blurb else "") + line[2:].strip()
            else:
                break
        items.append(
            {
                "id": key,
                "title": EXAMPLE_TITLES.get(key, key.title()),
                "blurb": blurb,
                "source": source,
            }
        )
        if verify:
            # The playground saves code as Main.geno; module names must be identifiers.
            with tempfile.TemporaryDirectory() as tmp:
                main = Path(tmp) / "Main.geno"
                main.write_text(source)
                for args in (["check"], ["test"]):
                    proc = subprocess.run(  # noqa: S603 - fixed argv: this interpreter, the geno CLI, a temp file
                        [sys.executable, "-m", "geno", *args, str(main)],
                        cwd=REPO,
                        capture_output=True,
                        text=True,
                    )
                    if proc.returncode != 0:
                        raise SystemExit(
                            f"example {path.name} failed `geno {args[0]}`:\n{proc.stdout}{proc.stderr}"
                        )
    out = SHARED / "js" / "examples.js"
    out.write_text(
        "/* Generated by website/build.py from website/shared/examples/*.geno. Do not edit. */\n"
        "window.GenoExamples = "
        + json.dumps(items, indent=1, ensure_ascii=False)
        + ";\n"
    )
    print(
        f"examples {out.relative_to(REPO)}  {len(items)} programs{' (verified)' if verify else ''}"
    )


# --------------------------------------------------------------------------
# 3. Blog
# --------------------------------------------------------------------------
@dataclass
class Post:
    slug: str
    title: str
    date: date
    author: str
    summary: str
    number: int
    tags: list[str] = field(default_factory=list)
    kicker: str = ""
    body: str = ""
    reading_minutes: int = 1

    @property
    def date_long(self) -> str:
        return f"{self.date:%B} {self.date.day}, {self.date.year}"

    @property
    def date_short(self) -> str:
        return self.date.strftime("%Y-%m-%d")


FRONT = re.compile(r"^\s*<!--(.*?)-->\s*", re.S)


def load_posts() -> list[Post]:
    posts = []
    for path in sorted((SHARED / "posts").glob("*.html")):
        text = path.read_text()
        m = FRONT.match(text)
        if not m:
            raise SystemExit(f"{path.name}: missing front matter comment")
        meta = {}
        for line in m.group(1).strip().splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip()
        body = text[m.end() :].strip()
        words = len(re.sub(r"<[^>]+>", " ", body).split())
        posts.append(
            Post(
                slug=meta.get("slug", path.stem),
                title=meta["title"],
                date=date.fromisoformat(meta["date"]),
                author=meta.get("author", "David Iach"),
                summary=meta.get("summary", ""),
                number=int(meta.get("number", "0")),
                tags=[t.strip() for t in meta.get("tags", "").split(",") if t.strip()],
                kicker=meta.get("kicker", ""),
                body=body,
                reading_minutes=max(1, round(words / 230)),
            )
        )
    posts.sort(key=lambda p: (p.date, p.number), reverse=True)
    return posts


def toc(body: str) -> tuple[str, str]:
    """Give each <h2> an id and return (body, toc_items_html)."""
    items = []

    def repl(m: re.Match) -> str:
        text = re.sub(r"<[^>]+>", "", m.group(2))
        slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
        items.append(f'<li><a href="#{slug}">{html.escape(text)}</a></li>')
        return f'<h2 id="{slug}"{m.group(1)}>{m.group(2)}</h2>'

    body = re.sub(r"<h2([^>]*)>(.*?)</h2>", repl, body)
    return body, "\n".join(items)


def fill(template: str, values: dict[str, str]) -> str:
    def repl(m: re.Match) -> str:
        key = m.group(1)
        if key not in values:
            raise SystemExit(f"template placeholder {{{{{key}}}}} has no value")
        return values[key]

    return re.sub(r"\{\{(\w+)\}\}", repl, template)


def post_values(p: Post, prev: Post | None, nxt: Post | None) -> dict[str, str]:
    body, toc_items = toc(p.body)
    return {
        "site_url": SITE_URL,
        "title": html.escape(p.title),
        "slug": p.slug,
        "summary": html.escape(p.summary),
        "author": html.escape(p.author),
        "date_long": p.date_long,
        "date_short": p.date_short,
        "number": f"{p.number:03d}",
        "kicker": html.escape(p.kicker or (p.tags[0].title() if p.tags else "Notes")),
        "tags": " ".join(f'<span class="tag">{html.escape(t)}</span>' for t in p.tags),
        "reading": f"{p.reading_minutes} min read",
        "body": body,
        "toc": toc_items,
        "prev_link": (
            f'<a class="pager-prev" href="{prev.slug}.html"><span>Older</span>{html.escape(prev.title)}</a>'
            if prev
            else "<span></span>"
        ),
        "next_link": (
            f'<a class="pager-next" href="{nxt.slug}.html"><span>Newer</span>{html.escape(nxt.title)}</a>'
            if nxt
            else "<span></span>"
        ),
    }


def rss(posts: list[Post]) -> str:
    base = f"{SITE_URL}/blog"
    items = []
    for p in posts:
        dt = datetime(p.date.year, p.date.month, p.date.day, 12, tzinfo=timezone.utc)
        items.append(
            "  <item>\n"
            f"    <title>{html.escape(p.title)}</title>\n"
            f"    <link>{base}/{p.slug}.html</link>\n"
            f"    <guid>{base}/{p.slug}.html</guid>\n"
            f"    <pubDate>{format_datetime(dt)}</pubDate>\n"
            f"    <description>{html.escape(p.summary)}</description>\n"
            "  </item>"
        )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n<rss version="2.0">\n<channel>\n'
        "  <title>Geno</title>\n"
        f"  <link>{base}/</link>\n"
        "  <description>Notes, releases and design writing from the Geno project.</description>\n"
        + "\n".join(items)
        + "\n</channel>\n</rss>\n"
    )


def sitemap(posts: list[Post]) -> str:
    urls = [f"{SITE_URL}/", f"{SITE_URL}/playground.html", f"{SITE_URL}/blog/"]
    urls += [f"{SITE_URL}/blog/{p.slug}.html" for p in posts]
    rows = "\n".join(f"  <url><loc>{u}</loc></url>" for u in urls)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{rows}\n</urlset>\n"
    )


def build_blog() -> None:
    posts = load_posts()
    tdir = SITE / "_templates"
    out = SITE / "blog"
    out.mkdir(parents=True, exist_ok=True)
    post_t = (tdir / "post.html").read_text()
    index_t = (tdir / "blog.html").read_text()
    row_t = (tdir / "blog-row.html").read_text()
    card_t = (tdir / "blog-card.html").read_text()
    for i, p in enumerate(posts):
        older = posts[i + 1] if i + 1 < len(posts) else None
        newer = posts[i - 1] if i > 0 else None
        (out / f"{p.slug}.html").write_text(fill(post_t, post_values(p, older, newer)))
    rows = "\n".join(fill(row_t, post_values(p, None, None)) for p in posts)
    (out / "index.html").write_text(
        fill(index_t, {"site_url": SITE_URL, "rows": rows, "count": str(len(posts))})
    )
    (out / "feed.xml").write_text(rss(posts))
    (SITE / "sitemap.xml").write_text(sitemap(posts))
    (SITE / "robots.txt").write_text(
        f"User-agent: *\nAllow: /\n\nSitemap: {SITE_URL}/sitemap.xml\n"
    )
    landing = SITE / "index.html"
    cards = "\n".join(fill(card_t, post_values(p, None, None)) for p in posts[:3])
    text = landing.read_text()
    new, n = re.subn(
        r"(<!-- blog:latest -->).*?(<!-- /blog:latest -->)",
        lambda m: m.group(1) + "\n" + cards + "\n" + m.group(2),
        text,
        flags=re.S,
    )
    if n:
        landing.write_text(new)
    print(f"blog     {len(posts)} posts")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument(
        "--verify",
        action="store_true",
        help="check and test every example with the local geno",
    )
    ap.add_argument(
        "--no-bundle", action="store_true", help="skip the playground bundle"
    )
    args = ap.parse_args()
    if not args.no_bundle:
        build_bundle()
    build_examples(args.verify)
    build_blog()


if __name__ == "__main__":
    main()

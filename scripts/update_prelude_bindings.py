#!/usr/bin/env python3
"""Regenerate the exact-source runtime prelude binding inventory."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from geno.compiler import _uncached_python_prelude_binding_names  # noqa: E402
from geno.runtime_prelude import RUNTIME_PRELUDE  # noqa: E402

OUTPUT = ROOT / "geno" / "_prelude_bindings.py"


def render_bindings(source: str) -> str:
    """Generate raw module bindings; compiler policy remains in compiler.py."""
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    names = _uncached_python_prelude_binding_names(source)
    lines = [
        '"""Generated by scripts/update_prelude_bindings.py; do not edit manually."""',
        "",
        "PRELUDE_SOURCE_SHA256 = (",
        f'    "{digest}"',
        ")",
        "",
        "PRELUDE_BINDING_NAMES = frozenset(",
        "    {",
        *(f"        {json.dumps(name)}," for name in sorted(names)),
        "    }",
        ")",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if generated data is stale"
    )
    args = parser.parse_args()
    expected = render_bindings(RUNTIME_PRELUDE)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != expected:
            print(
                "Prelude inventory is stale; run python scripts/update_prelude_bindings.py",
                file=sys.stderr,
            )
            return 1
        print("Prelude binding inventory is current")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"Updated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
